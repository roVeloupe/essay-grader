export function icon(name, cls = '') {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  if (cls) svg.setAttribute('class', cls);
  svg.innerHTML = ICONS[name] || '';
  return svg;
}

export function toast(message, kind = 'info', ms = 3200) {
  const stack = $('#toasts');
  const el = h('div', { class: 'toast', 'data-kind': kind, text: message });
  stack.append(el);
  setTimeout(() => { el.style.opacity = '0'; el.style.transform = 'translateY(4px)'; el.style.transition = 'all .2s'; }, ms - 220);
  setTimeout(() => el.remove(), ms);
}

export function fmtDate(iso) {
  if (!iso) return '';
  const d = new Date(iso);
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getMonth() + 1}月${d.getDate()}日 ${p(d.getHours())}:${p(d.getMinutes())}`;
}

export function statusOf(p) {
  if (p.status === 'graded') return { text: `${p.grade?.total ?? '-'} / ${p.grade ? '' : ''}`, cls: 'ok' };
  if (p.status === 'error') return { text: '失败', cls: 'err' };
  if (p.status === 'running') return { text: p.progress?.stage === 'grade' ? '批阅中' : p.progress?.stage === 'correct' ? '校对中' : '识别中', cls: 'warn' };
  return { text: '待批改', cls: '' };
}

export function debounce(fn, ms = 300) {
  let t;
  return (...args) => { clearTimeout(t); t = setTimeout(() => fn(...args), ms); };
}

export function escapeHtml(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
